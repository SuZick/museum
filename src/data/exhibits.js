// Найти экспонат по id (используется на странице экспоната)
export function findExhibit(id) {
  return exhibits.find((exhibit) => exhibit.id === id)
}

// Экспонаты одной эпохи (используется на главной)
export function exhibitsOfEra(eraId) {
  return exhibits.filter((exhibit) => exhibit.era === eraId)
}

// Порядковый номер экспоната в каталоге: 1 → «№ 01»
export function catalogNumber(exhibit) {
  const index = exhibits.indexOf(exhibit) + 1
  return '№ ' + String(index).padStart(2, '0')
}
